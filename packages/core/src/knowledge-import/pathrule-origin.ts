// Did Pathrule write this file? The import's answer.
//
// Importing a folder's instruction files must never take in what Pathrule wrote
// there. A sync writes the protocol and compiled knowledge into the same files a
// person keeps their own instructions in, and a file written from Pathrule Cloud
// carries Cloud content: importing it would put that content into the Local
// store. So the import reads only what is provably the person's, and a file
// whose origin cannot be told is not assumed to be theirs.
//
// A file counts as Pathrule's when any of these holds:
//   - its path is one only Pathrule's renderers write;
//   - `.pathrule/managed-files.json` lists it;
//   - it carries a Pathrule banner or marker outside an intact region.
// An intact `pathrule:begin` ... `pathrule:end` region is cut out and the rest is
// the person's. A region marker without its partner leaves the bounds unknown,
// so nothing in that file is imported.
//
// Pure (no fs): discovery.ts reads the files and the ledger and asks here.

/** Why the import left a file out. */
export type PathruleOriginReason =
  /** A path only Pathrule's renderers write, or a file holding nothing but Pathrule's region. */
  | "pathrule_written"
  /** A Pathrule banner or marker outside an intact region. */
  | "pathrule_banner"
  /** `.pathrule/managed-files.json` records Pathrule writing it, and no region says which bytes. */
  | "managed_file"
  /** A region marker without its partner, or nested ones: where Pathrule's bytes end is unknown. */
  | "unbalanced_marker";

/**
 * Every banner and marker Pathrule writes into a file, as the substring that
 * identifies it. The one list the import checks. Matched ignoring case and the
 * width of whitespace, so an older spelling of the same banner still counts.
 * `PATHRULE_MANAGED_MARKERS` (paths/ownership.ts, shared by every writer) must
 * stay covered by this list; a test checks it.
 */
export const PATHRULE_ORIGIN_MARKERS = [
  // integrations client-renderers/body.ts: the banner line that heads renderProtocolBody and
  // renderCompanionSignature ("... do not edit; cloud state is authoritative. -->"), which the
  // codex, cursor, windsurf and copilot renderers write and claude-md-project.ts writes in
  // signature mode. copilot-renderer.ts scopedPointerBody writes the same line.
  // knowledge-files.ts KNOWLEDGE_BANNER starts "<!-- Pathrule managed (knowledge)".
  "<!-- Pathrule managed",
  // integrations claude-md-project.ts BANNER, the root CLAUDE.md ("... do not edit this file
  // manually. Cloud state is authoritative. Local edits are overwritten. -->").
  "<!-- managed by Pathrule",
  // integrations client-renderers/claude-knowledge-renderer.ts BINDING_IGNORE, the .gitignore in
  // `.claude/rules/pathrule/` ("... compiled instructions, regenerated on sync.").
  "# Pathrule managed",
  // "# >>> Pathrule managed": eject.ts GITIGNORE_START, pathrule-protocol.ts CODEX_TOML_START
  // ("# >>> Pathrule managed (codex hook activation) >>>"), claude-knowledge-renderer.ts
  // BINDING_MANIFEST ("# >>> Pathrule managed: binding manifest").
  "# >>> Pathrule managed",
  // "# <<< Pathrule managed <<<": pathrule-protocol.ts CODEX_TOML_END, eject.ts's block end.
  "# <<< Pathrule managed",
  // integrations client-renderers/promoted-rules-section.ts: PROMOTED_RULES_ANCHOR_BEGIN,
  // PROMOTED_RULES_ANCHOR_END and the signature comment every renderer splices in.
  "<!-- pathrule:promoted-rules:begin",
  "<!-- pathrule:promoted-rules:end",
  "<!-- pathrule:promoted-rules-signature=",
  // core paths/region.ts PATHRULE_REGION, which safe-write.ts writes through mergeRegionInto for
  // its "merge-region" files. An intact pair is cut out before this list is checked, so one left
  // over here never happens: the region scan reports it as unbalanced first.
  "<!-- pathrule:begin",
  "<!-- pathrule:end",
] as const;

const MARKER_RES = PATHRULE_ORIGIN_MARKERS.map(
  (marker) => new RegExp(marker.replace(/[.*+?^${}()|[\]\\]/g, "\\$&").replace(/ /g, "\\s*"), "i"),
);

/** True when the text carries any Pathrule banner or marker. */
export function hasPathruleMarker(text: string): boolean {
  return MARKER_RES.some((re) => re.test(text));
}

/**
 * Paths only Pathrule writes, so the name alone settles it. Workspace-relative,
 * forward slashes; a tool folder nested in a package counts as one at the root.
 */
const PATHRULE_WRITTEN_PATHS: readonly RegExp[] = [
  // eject.ts isPathruleOwnedName: Pathrule's own folder (ledger, backups, caches).
  /(^|\/)\.pathrule(\/|$)/,
  // claude-protocol-file.ts CLAUDE_PROTOCOL_FILE (`.claude/rules/pathrule-protocol.md`),
  // claude-knowledge-renderer.ts ROOT_KNOWLEDGE_PATH (`.claude/rules/pathrule-knowledge.md`);
  // eject.ts isPathruleOwnedName.
  /(^|\/)\.claude\/rules\/(.+\/)?pathrule-[^/]*$/,
  // claude-knowledge-renderer.ts BINDING_DIR: `.claude/rules/pathrule/` (workspace.md, a file
  // per area, .gitignore, manifest.json).
  /(^|\/)\.claude\/rules\/pathrule\//,
  // cursor-renderer.ts MODERN_PATH (`pathrule-protocol.mdc`) and knowledgePath
  // (`pathrule-k-<slug>.mdc`); eject.ts isPathruleOwnedName.
  /(^|\/)\.cursor\/rules\/(.+\/)?pathrule-[^/]*$/,
  // windsurf-renderer.ts MODERN_PATH (`pathrule-protocol.md`) and knowledgePath
  // (`pathrule-k-<slug>.md`); eject.ts isPathruleOwnedName.
  /(^|\/)\.windsurf\/rules\/(.+\/)?pathrule-[^/]*$/,
  // copilot-renderer.ts SCOPED_PATH (`pathrule.instructions.md`) and knowledgePath
  // (`pathrule-k-<slug>.instructions.md`); eject.ts isPathruleOwnedName (`pathrule-*`).
  /(^|\/)\.github\/instructions\/(.+\/)?pathrule[-.][^/]*$/,
  // copilot-renderer.ts HOOKS_PATH; eject.ts isPathruleOwnedName.
  /(^|\/)\.github\/hooks\/pathrule\.json$/,
  // legacy-sweep.ts ORPHANED_PATHRULE_FILES: what an older Pathrule wrote under `.agents/rules/`.
  /(^|\/)\.agents\/rules\/(.+\/)?pathrule-[^/]*$/,
];

/** True when only Pathrule writes a file at this path. */
export function isPathruleWrittenPath(relativePath: string): boolean {
  return PATHRULE_WRITTEN_PATHS.some((re) => re.test(relativePath));
}

/**
 * Files Pathrule shares with the person: it owns a region inside and never a
 * byte outside it, so a ledger entry for one means "Pathrule wrote the region".
 * safe-write.ts SAFE_WRITE_POLICIES "merge-region" entries, and its
 * fallbackPolicy for a CLAUDE.md or AGENTS.md at any depth.
 */
function isRegionFile(relativePath: string): boolean {
  const base = relativePath.slice(relativePath.lastIndexOf("/") + 1);
  if (base === "CLAUDE.md" || base === "AGENTS.md") return true;
  return relativePath === ".cursorrules" || relativePath === ".windsurfrules";
}

/** A `pathrule:begin` or `pathrule:end` comment, however it is spaced or cased. */
const REGION_MARKER_RE = /<!--\s*pathrule:(begin|end)\b/gi;

export type RegionScan =
  /** Every marker paired in order. `outside` is the text with each region cut out. */
  | { balanced: true; outside: string; regions: number }
  /** A begin with no end, an end with no begin, nested markers, or a marker never closed. */
  | { balanced: false };

/**
 * Cut every intact Pathrule region out of a body. One region leaves the same
 * text `stripRegion` (paths/region.ts) does; unlike it, a lone marker is not
 * guessed around: stripRegion keeps everything before an end with no begin,
 * which is Pathrule's own text once the begin line is gone.
 */
export function scanPathruleRegions(body: string): RegionScan {
  const kept: string[] = [];
  let cursor = 0;
  let open = false;
  let regions = 0;
  for (const match of body.matchAll(REGION_MARKER_RE)) {
    const start = match.index ?? 0;
    const close = body.indexOf("-->", start);
    const lineEnd = body.indexOf("\n", start);
    // A marker comment that never closes on its own line has no bounds to trust.
    if (close < 0 || (lineEnd >= 0 && close > lineEnd)) return { balanced: false };
    if (match[1]!.toLowerCase() === "begin") {
      if (open) return { balanced: false }; // nested
      kept.push(body.slice(cursor, start));
      open = true;
    } else {
      if (!open) return { balanced: false }; // end with no begin
      cursor = close + "-->".length;
      open = false;
      regions += 1;
    }
  }
  if (open) return { balanced: false }; // begin with no end
  if (regions === 0) return { balanced: true, outside: body, regions };
  kept.push(body.slice(cursor));
  const outside = kept
    .map((part) => part.trim())
    .filter((part) => part !== "")
    .join("\n");
  return { balanced: true, outside, regions };
}

export type OriginVerdict =
  /** The person's text, with Pathrule's region cut out. */
  { import: true; content: string } | { import: false; reason: PathruleOriginReason };

/**
 * What of this file the import may take. `managedPaths` is the ledger's list,
 * normalised the way its writer stores paths.
 */
export function judgePathruleOrigin(input: {
  path: string;
  body: string;
  managedPaths: ReadonlySet<string>;
}): OriginVerdict {
  if (isPathruleWrittenPath(input.path)) return { import: false, reason: "pathrule_written" };

  const scan = scanPathruleRegions(input.body);
  if (!scan.balanced) return { import: false, reason: "unbalanced_marker" };
  // A legacy banner-only file, a banner-carrying copilot-instructions.md, or Pathrule's text
  // pasted or left outside a region: any of it outside a region makes the whole file uncertain.
  if (hasPathruleMarker(scan.outside)) return { import: false, reason: "pathrule_banner" };

  // The ledger says Pathrule wrote here. Only a shared file whose region accounts for what
  // Pathrule wrote has bytes that are provably the person's.
  if (input.managedPaths.has(input.path) && !(scan.regions > 0 && isRegionFile(input.path))) {
    return { import: false, reason: "managed_file" };
  }
  if (scan.regions > 0 && scan.outside.trim() === "") {
    return { import: false, reason: "pathrule_written" };
  }
  return { import: true, content: scan.outside };
}
