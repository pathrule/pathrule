// The import's answer to "did Pathrule write this file?". Fixtures are built the
// way Pathrule's writers build them (mergeRegionInto, the renderers' banners),
// so a change to a writer that this module does not follow shows up here.

import { describe, expect, it } from "vitest";

import { PATHRULE_MANAGED_MARKERS } from "../paths/ownership.js";
import { PATHRULE_REGION, mergeRegionInto, stripRegion } from "../paths/region.js";
import {
  PATHRULE_ORIGIN_MARKERS,
  hasPathruleMarker,
  isPathruleWrittenPath,
  judgePathruleOrigin,
  scanPathruleRegions,
} from "./pathrule-origin.js";

// The renderers' banners, spelled as they write them (U+2014 is their dash).
const CLIENT_BANNER = "<!-- Pathrule managed \u2014 do not edit; cloud state is authoritative. -->";
const ROOT_BANNER =
  "<!-- managed by Pathrule \u2014 do not edit this file manually. Cloud state is authoritative. Local edits are overwritten. -->";
const KNOWLEDGE_BANNER =
  "<!-- Pathrule managed (knowledge) \u2014 compiled from workspace knowledge; do not edit; regenerated on sync. -->";

const PERSON = "# Acme\n\n## Style\n\nUse camelCase.\n";
const CLOUD_BODY = `${CLIENT_BANNER}\n\n# Pathrule integration\n\n## Workspace knowledge (Pathrule)\n\nCloud says hi.\n`;

const none = new Set<string>();
const judge = (path: string, body: string, managed: ReadonlySet<string> = none) =>
  judgePathruleOrigin({ path, body, managedPaths: managed });

describe("PATHRULE_ORIGIN_MARKERS", () => {
  it("covers every banner the writers share in paths/ownership.ts", () => {
    for (const marker of PATHRULE_MANAGED_MARKERS) {
      expect(hasPathruleMarker(marker)).toBe(true);
    }
  });

  it("recognises each banner and marker the renderers write", () => {
    for (const banner of [
      CLIENT_BANNER,
      ROOT_BANNER,
      KNOWLEDGE_BANNER,
      "# Pathrule managed \u2014 compiled instructions, regenerated on sync.",
      "# >>> Pathrule managed (codex hook activation) >>>",
      "# <<< Pathrule managed <<<",
      "<!-- pathrule:promoted-rules:begin -->",
      "<!-- pathrule:promoted-rules:end -->",
      "<!-- pathrule:promoted-rules-signature=abc123 -->",
      PATHRULE_REGION.begin,
      PATHRULE_REGION.end,
    ]) {
      expect(hasPathruleMarker(`Some text\n${banner}\nmore`)).toBe(true);
    }
    expect(PATHRULE_ORIGIN_MARKERS.length).toBeGreaterThan(0);
  });

  it("tolerates an older spelling's case and spacing", () => {
    expect(hasPathruleMarker("<!--pathrule  MANAGED -->")).toBe(true);
  });

  it("finds nothing in a person's ordinary instructions", () => {
    expect(hasPathruleMarker(PERSON)).toBe(false);
    expect(hasPathruleMarker("We use Pathrule for team memory. Manage it with care.")).toBe(false);
  });
});

describe("isPathruleWrittenPath", () => {
  it("names every path only Pathrule's renderers write", () => {
    for (const path of [
      ".claude/rules/pathrule-protocol.md",
      ".claude/rules/pathrule-knowledge.md",
      ".claude/rules/nested/pathrule-extra.md",
      ".claude/rules/pathrule/workspace.md",
      ".claude/rules/pathrule/apps-api.md",
      ".cursor/rules/pathrule-protocol.mdc",
      ".cursor/rules/pathrule-k-apps-api.mdc",
      ".windsurf/rules/pathrule-protocol.md",
      ".windsurf/rules/pathrule-k-root.md",
      ".github/instructions/pathrule.instructions.md",
      ".github/instructions/pathrule-k-apps-api.instructions.md",
      ".github/hooks/pathrule.json",
      ".agents/rules/pathrule-protocol.md",
      ".pathrule/backups/CLAUDE.md",
      "packages/api/.cursor/rules/pathrule-protocol.mdc",
    ]) {
      expect(isPathruleWrittenPath(path), path).toBe(true);
    }
  });

  it("leaves the person's own names and shared files to the content checks", () => {
    for (const path of [
      "CLAUDE.md",
      "AGENTS.md",
      ".cursorrules",
      ".github/copilot-instructions.md",
      ".github/instructions/api.instructions.md",
      ".claude/rules/testing.md",
      ".cursor/rules/backend.mdc",
      "docs/pathrule-notes.md",
    ]) {
      expect(isPathruleWrittenPath(path), path).toBe(false);
    }
  });
});

describe("scanPathruleRegions", () => {
  it("cuts one region out exactly as stripRegion does", () => {
    const body = mergeRegionInto(PERSON, CLOUD_BODY);
    const scan = scanPathruleRegions(body);
    expect(scan).toEqual({ balanced: true, outside: stripRegion(body), regions: 1 });
  });

  it("returns a body with no markers untouched", () => {
    expect(scanPathruleRegions(PERSON)).toEqual({ balanced: true, outside: PERSON, regions: 0 });
  });

  it("cuts two regions that each close before the next opens", () => {
    const region = `${PATHRULE_REGION.begin}\nours\n${PATHRULE_REGION.end}`;
    const scan = scanPathruleRegions(`a\n${region}\nb\n${region}\nc\n`);
    expect(scan).toEqual({ balanced: true, outside: "a\nb\nc", regions: 2 });
  });

  it.each([
    ["an end with no begin", `mine\n\nCloud text\n${PATHRULE_REGION.end}\n`],
    ["a begin with no end", `mine\n${PATHRULE_REGION.begin}\nCloud text\n`],
    [
      "nested markers",
      `${PATHRULE_REGION.begin}\n${PATHRULE_REGION.begin}\nx\n${PATHRULE_REGION.end}\n${PATHRULE_REGION.end}\n`,
    ],
    [
      "a second begin before the first closes",
      `${PATHRULE_REGION.begin}\nx\n${PATHRULE_REGION.begin}\ny\n${PATHRULE_REGION.end}\n`,
    ],
    [
      "an end after a closed region",
      `${PATHRULE_REGION.begin}\nx\n${PATHRULE_REGION.end}\nmine\n${PATHRULE_REGION.end}\n`,
    ],
    [
      "a marker comment never closed",
      "mine\n<!-- pathrule:begin (managed\nx\n<!-- pathrule:end -->\n",
    ],
  ])("finds %s unbalanced", (_label, body) => {
    expect(scanPathruleRegions(body)).toEqual({ balanced: false });
  });
});

describe("judgePathruleOrigin", () => {
  it("imports a person's file word for word", () => {
    expect(judge("CLAUDE.md", PERSON)).toEqual({ import: true, content: PERSON });
  });

  it("declines a file by name before reading anything in it", () => {
    expect(judge(".cursor/rules/pathrule-protocol.mdc", PERSON)).toEqual({
      import: false,
      reason: "pathrule_written",
    });
  });

  it("declines a banner-only file from before regions existed", () => {
    expect(judge("CLAUDE.md", `${ROOT_BANNER}\n\n# Pathrule Workspace\n\nCloud text.\n`)).toEqual({
      import: false,
      reason: "pathrule_banner",
    });
  });

  it("keeps only the person's text around an intact region", () => {
    expect(judge("AGENTS.md", mergeRegionInto(PERSON, CLOUD_BODY))).toEqual({
      import: true,
      content: PERSON.trim(),
    });
  });

  it("declines a file holding nothing but Pathrule's region", () => {
    expect(
      judge("packages/api/CLAUDE.md", mergeRegionInto(null, `${KNOWLEDGE_BANNER}\nx\n`)),
    ).toEqual({
      import: false,
      reason: "pathrule_written",
    });
  });

  it("declines a file whose region lost its begin marker", () => {
    const body = mergeRegionInto(PERSON, CLOUD_BODY).replace(`${PATHRULE_REGION.begin}\n`, "");
    expect(judge("CLAUDE.md", body)).toEqual({ import: false, reason: "unbalanced_marker" });
  });

  it("declines a banner left outside the region", () => {
    const body = `${mergeRegionInto(PERSON, CLOUD_BODY)}\n${CLIENT_BANNER}\nPasted.\n`;
    expect(judge("CLAUDE.md", body)).toEqual({ import: false, reason: "pathrule_banner" });
  });

  it("declines a file the ledger lists, whatever it says", () => {
    expect(
      judge(".claude/rules/testing.md", PERSON, new Set([".claude/rules/testing.md"])),
    ).toEqual({
      import: false,
      reason: "managed_file",
    });
    expect(judge("CLAUDE.md", PERSON, new Set(["CLAUDE.md"]))).toEqual({
      import: false,
      reason: "managed_file",
    });
  });

  it("keeps the person's text in a shared file the ledger lists when its region is intact", () => {
    const body = mergeRegionInto(PERSON, CLOUD_BODY);
    expect(judge("CLAUDE.md", body, new Set(["CLAUDE.md"]))).toEqual({
      import: true,
      content: PERSON.trim(),
    });
  });

  it("does not let a region excuse a ledger entry on a file Pathrule overwrites whole", () => {
    const body = mergeRegionInto(PERSON, CLOUD_BODY);
    const path = ".github/copilot-instructions.md";
    expect(judge(path, body, new Set([path]))).toEqual({ import: false, reason: "managed_file" });
  });
});
