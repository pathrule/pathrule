// The eject plan. Read-only: every test asserts the disk is untouched afterwards,
// because a planner that mutates is a planner nobody will run twice.
import { mkdir, mkdtemp, readFile, rm, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { afterEach, describe, expect, it } from "vitest";

import { applyEject, planEject } from "./eject.js";

const roots: string[] = [];
afterEach(async () => {
  await Promise.all(roots.splice(0).map((r) => rm(r, { recursive: true, force: true, maxRetries: 10, retryDelay: 100 })));
});

const BANNER = "<!-- managed by Pathrule — do not edit this file manually. -->";
const REGION_OPEN = "<!-- pathrule:begin (managed by Pathrule; edits inside this region are overwritten) -->";
const REGION_CLOSE = "<!-- pathrule:end -->";

async function repo(files: Record<string, string>): Promise<string> {
  const root = await mkdtemp(join(tmpdir(), "pathrule-eject-"));
  roots.push(root);
  for (const [rel, body] of Object.entries(files)) {
    const abs = join(root, rel);
    await mkdir(join(abs, ".."), { recursive: true });
    await writeFile(abs, body);
  }
  return root;
}

const find = (plan: Awaited<ReturnType<typeof planEject>>, path: string) =>
  plan.actions.find((a) => a.path === path);

describe("planEject", () => {
  it("strips a region from the user's file but deletes a file that is entirely ours", async () => {
    const root = await repo({
      "CLAUDE.md": `# My project\n\nUse pnpm.\n\n${REGION_OPEN}\ncompiled knowledge\n${REGION_CLOSE}\n`,
      "packages/api/CLAUDE.md": `${BANNER}\n# Project knowledge\n`,
    });
    const plan = await planEject(root);

    expect(find(plan, "CLAUDE.md")?.kind).toBe("strip_region");
    expect(find(plan, "packages/api/CLAUDE.md")?.kind).toBe("delete_file");
  });

  it("never touches a file that has no Pathrule marker", async () => {
    const root = await repo({ "CLAUDE.md": "# Mine alone\n", "AGENTS.md": "# Also mine\n" });
    const plan = await planEject(root);
    expect(plan.actions).toEqual([]);
  });

  it("deletes files Pathrule invented the name of, marker or not", async () => {
    const root = await repo({
      ".claude/rules/pathrule-knowledge.md": "anything at all\n",
      ".cursor/rules/pathrule-protocol.mdc": "anything\n",
      ".github/hooks/pathrule.json": "{}\n",
      ".claude/rules/team-conventions.md": "the user's own rule file\n",
    });
    const plan = await planEject(root);

    for (const p of [
      ".claude/rules/pathrule-knowledge.md",
      ".cursor/rules/pathrule-protocol.mdc",
      ".github/hooks/pathrule.json",
    ]) {
      expect(find(plan, p)?.kind, p).toBe("delete_file");
    }
    // A rule file the USER wrote in the same directory is not ours to remove.
    expect(find(plan, ".claude/rules/team-conventions.md")).toBeUndefined();
  });

  it("unhooks a config the user owns instead of deleting it", async () => {
    const root = await repo({
      ".claude/settings.json": JSON.stringify({
        permissions: { allow: ["Bash"] },
        hooks: { UserPromptSubmit: [{ hooks: [{ command: "/x/pathrule-hook.js" }] }] },
      }),
      ".codex/config.toml": '[hooks]\ncommand = "pathrule-hook.js"\n',
    });
    const plan = await planEject(root);
    expect(find(plan, ".claude/settings.json")?.kind).toBe("unhook");
    expect(find(plan, ".codex/config.toml")?.kind).toBe("unhook");
  });

  it("strips the marker-bound block from .gitignore and leaves a clean one alone", async () => {
    const root = await repo({
      ".gitignore": "node_modules\n# >>> Pathrule managed (auto-generated, do not edit) >>>\n.pathrule/\n# <<< Pathrule managed <<<\n",
      "web/.gitignore": "dist\n",
    });
    const plan = await planEject(root);
    expect(find(plan, ".gitignore")?.kind).toBe("strip_block");
    expect(find(plan, "web/.gitignore")).toBeUndefined();
  });

  it("plans the Pathrule directory as one action, not a file list", async () => {
    const root = await repo({
      ".pathrule/managed-files.json": JSON.stringify({ schema_version: 1, files: [] }),
      ".pathrule/design/x/screen.html": "<div/>",
    });
    const plan = await planEject(root);
    const dirActions = plan.actions.filter((a) => a.path.startsWith(".pathrule"));
    expect(dirActions).toHaveLength(1);
    expect(dirActions[0]).toMatchObject({ path: ".pathrule", kind: "delete_file" });
  });

  it("restores a real backup and discards Pathrule's own, and says restores come first", async () => {
    const root = await repo({
      "backup.AGENTS.md": "# The user's real instructions\n",
      "AGENTS.md": `${BANNER}\n# Project knowledge\n`,
      "packages/mobile/backup.CLAUDE.md": `${BANNER}\n# Pathrule Workspace\n`,
      "packages/mobile/CLAUDE.md": `${BANNER}\n# Project knowledge\n`,
    });
    const plan = await planEject(root);

    expect(find(plan, "backup.AGENTS.md")).toMatchObject({
      kind: "restore_backup",
      target: "AGENTS.md",
    });
    expect(find(plan, "packages/mobile/backup.CLAUDE.md")?.kind).toBe("discard_backup");
    expect(plan.restoresFirst).toBe(true);
  });

  it("reports a ledger entry that is already gone instead of failing", async () => {
    const root = await repo({
      ".pathrule/managed-files.json": JSON.stringify({
        schema_version: 1,
        files: [{ path: "packages/gone/CLAUDE.md", owner: "desktop", owner_version: "1", updated_at: "x" }],
      }),
    });
    const plan = await planEject(root);
    expect(plan.missing).toContain("packages/gone/CLAUDE.md");
  });

  it("survives a corrupt ledger by falling back to the content walk", async () => {
    const root = await repo({
      ".pathrule/managed-files.json": "{not json",
      "packages/api/AGENTS.md": `${BANNER}\n# Project knowledge\n`,
    });
    const plan = await planEject(root);
    expect(find(plan, "packages/api/AGENTS.md")?.kind).toBe("delete_file");
  });

  it("changes nothing on disk", async () => {
    const before = {
      "CLAUDE.md": `# Mine\n\n${REGION_OPEN}\nours\n${REGION_CLOSE}\n`,
      "packages/api/AGENTS.md": `${BANNER}\n# knowledge\n`,
      "backup.AGENTS.md": "# real\n",
      ".gitignore": "node_modules\n# >>> Pathrule managed (auto-generated, do not edit) >>>\n.pathrule/\n# <<< Pathrule managed <<<\n",
    };
    const root = await repo(before);
    await planEject(root);
    for (const [rel, body] of Object.entries(before)) {
      expect(await readFile(join(root, rel), "utf8"), rel).toBe(body);
    }
  });
});

// Apply. The properties that matter are not "it deletes things" but: the user's
// bytes survive, the order cannot strand their content, running it twice is the
// same as running it once, and a path from a stale ledger cannot escape.
describe("applyEject", () => {
  const exists = async (root: string, rel: string) => {
    const { access } = await import("node:fs/promises");
    try {
      await access(join(root, rel));
      return true;
    } catch {
      return false;
    }
  };

  it("keeps the user's bytes when it strips a region", async () => {
    const root = await repo({
      "CLAUDE.md": `# My project\n\nUse pnpm, never npm.\n\n${REGION_OPEN}\ncompiled knowledge\n${REGION_CLOSE}\n`,
    });
    const res = await applyEject(root, await planEject(root));
    expect(res.failed).toBe(0);

    const after = await readFile(join(root, "CLAUDE.md"), "utf8");
    expect(after).toContain("Use pnpm, never npm.");
    expect(after).not.toContain("compiled knowledge");
    expect(after).not.toContain("pathrule:begin");
  });

  it("restores the user's backup BEFORE removing the file it belongs to", async () => {
    const root = await repo({
      "backup.AGENTS.md": "# The real instructions\n",
      "AGENTS.md": `${BANNER}\n# Project knowledge\n`,
    });
    const res = await applyEject(root, await planEject(root));
    expect(res.failed).toBe(0);

    // The user's content is back at its own path, and the backup is gone.
    expect(await readFile(join(root, "AGENTS.md"), "utf8")).toBe("# The real instructions\n");
    expect(await exists(root, "backup.AGENTS.md")).toBe(false);
  });

  it("leaves a needs-choice restore for the user instead of picking a merge", async () => {
    const root = await repo({
      "backup.CLAUDE.md": "# The old instructions\n",
      "CLAUDE.md": `# The user wrote this too\n\n${REGION_OPEN}\nours\n${REGION_CLOSE}\n`,
    });
    const plan = await planEject(root);
    const res = await applyEject(root, plan);

    const restore = res.results.find((r) => r.action.kind === "restore_backup");
    expect(restore?.outcome).toBe("skipped");
    // Neither file lost anything.
    expect(await readFile(join(root, "backup.CLAUDE.md"), "utf8")).toBe("# The old instructions\n");
    expect(await readFile(join(root, "CLAUDE.md"), "utf8")).toContain("The user wrote this too");
  });

  it("removes only Pathrule's hook entries and keeps the rest of the config", async () => {
    const root = await repo({
      ".claude/settings.json": JSON.stringify(
        {
          permissions: { allow: ["Bash(git status)"] },
          hooks: {
            UserPromptSubmit: [
              { hooks: [{ type: "command", command: "/x/pathrule-hook.js" }] },
              { hooks: [{ type: "command", command: "/x/my-own-hook.sh" }] },
            ],
          },
        },
        null,
        2,
      ),
    });
    await applyEject(root, await planEject(root));

    const after = JSON.parse(await readFile(join(root, ".claude/settings.json"), "utf8"));
    expect(after.permissions.allow).toEqual(["Bash(git status)"]);
    expect(JSON.stringify(after)).not.toContain("pathrule-hook");
    expect(JSON.stringify(after)).toContain("my-own-hook.sh");
  });

  it("strips the .gitignore block and keeps the user's lines", async () => {
    const root = await repo({
      ".gitignore": "node_modules\ndist\n# >>> Pathrule managed (auto-generated, do not edit) >>>\n.pathrule/\n# <<< Pathrule managed <<<\ncoverage\n",
    });
    await applyEject(root, await planEject(root));
    const after = await readFile(join(root, ".gitignore"), "utf8");
    expect(after).toContain("node_modules");
    expect(after).toContain("coverage");
    expect(after).not.toContain("Pathrule managed");
  });

  it("is idempotent: applying twice ends where applying once did", async () => {
    const files = {
      "CLAUDE.md": `# Mine\n\n${REGION_OPEN}\nours\n${REGION_CLOSE}\n`,
      "packages/api/AGENTS.md": `${BANNER}\n# knowledge\n`,
      ".pathrule/managed-files.json": JSON.stringify({ schema_version: 1, files: [] }),
      ".gitignore": "node_modules\n# >>> Pathrule managed (auto-generated, do not edit) >>>\n.pathrule/\n# <<< Pathrule managed <<<\n",
    };
    const root = await repo(files);
    await applyEject(root, await planEject(root));
    const firstPass = {
      claude: await readFile(join(root, "CLAUDE.md"), "utf8"),
      gitignore: await readFile(join(root, ".gitignore"), "utf8"),
      api: await exists(root, "packages/api/AGENTS.md"),
      dir: await exists(root, ".pathrule"),
    };

    const second = await applyEject(root, await planEject(root));
    expect(second.failed).toBe(0);
    expect(await readFile(join(root, "CLAUDE.md"), "utf8")).toBe(firstPass.claude);
    expect(await readFile(join(root, ".gitignore"), "utf8")).toBe(firstPass.gitignore);
    expect(await exists(root, "packages/api/AGENTS.md")).toBe(firstPass.api);
    expect(await exists(root, ".pathrule")).toBe(firstPass.dir);
  });

  // The planner no longer emits this pair, but a plan built before a recovery and
  // applied after still can. Deleting a file a restore just wrote is the worst
  // outcome eject has, so apply refuses it independently of the planner.
  it("refuses to delete a path it just restored, even from a self-contradicting plan", async () => {
    const root = await repo({
      "backup.AGENTS.md": "# The real instructions\n",
      "AGENTS.md": `${BANNER}\n# Project knowledge\n`,
    });
    const res = await applyEject(root, {
      actions: [
        { kind: "delete_file", path: "AGENTS.md", bytes: 0, reason: "stale plan" },
        {
          kind: "restore_backup",
          path: "backup.AGENTS.md",
          target: "AGENTS.md",
          bytes: 0,
          reason: "your content is in here; put it back",
        },
      ],
      missing: [],
      restoresFirst: true,
      heldForRecovery: [], unclear: [],
    });

    expect(await readFile(join(root, "AGENTS.md"), "utf8")).toBe("# The real instructions\n");
    expect(res.results.find((r) => r.action.kind === "delete_file")?.outcome).toBe("skipped");
  });

  // The worst outcome eject can have, found by asking what happens to a SKIPPED
  // restore that lives inside a directory we delete. `.pathrule/backups/` is
  // inside `.pathrule`, so a needs-choice vault backup was destroyed by the
  // directory delete after apply had just decided not to touch it. That backup
  // can be the user's only copy.
  it("does not delete a directory that still holds a backup it skipped", async () => {
    const root = await repo({
      // The user's only copy, in the vault.
      ".pathrule/backups/packages/api/CLAUDE.md": "# The user's ONLY copy\n",
      // The live file also holds their content, which is what makes the restore a
      // needs-choice rather than something apply may do on its own.
      "packages/api/CLAUDE.md": `# also mine\n\n${REGION_OPEN}\nours\n${REGION_CLOSE}\n`,
      "CLAUDE.md": `${BANNER}\n# ours\n`,
    });

    const plan = await planEject(root);
    const res = await applyEject(root, plan);

    expect(res.failed).toBe(0);
    // The vault survives, with the user's bytes intact.
    expect(await readFile(join(root, ".pathrule/backups/packages/api/CLAUDE.md"), "utf8")).toBe(
      "# The user's ONLY copy\n",
    );
    // And the plan says why it held back, so this is not silent.
    expect(plan.heldForRecovery).toContain(".pathrule/backups/packages/api/CLAUDE.md");
    // Everything else still happened.
    expect(await exists(root, "CLAUDE.md")).toBe(false);
    expect(await readFile(join(root, "packages/api/CLAUDE.md"), "utf8")).toContain("also mine");
  });

  it("still removes the Pathrule directory once nothing of the user's is inside it", async () => {
    const root = await repo({
      ".pathrule/managed-files.json": JSON.stringify({ schema_version: 1, files: [] }),
      "CLAUDE.md": `${BANNER}\n# ours\n`,
    });
    const plan = await planEject(root);
    expect(plan.heldForRecovery).toEqual([]);
    await applyEject(root, plan);
    expect(await exists(root, ".pathrule")).toBe(false);
  });

  it("refuses a path that escapes the workspace", async () => {
    const root = await repo({ "CLAUDE.md": `${BANNER}\nours\n` });
    const res = await applyEject(root, {
      actions: [
        { kind: "delete_file", path: "../../etc/hosts", bytes: 0, reason: "a stale ledger entry" },
      ],
      missing: [],
      restoresFirst: false,
      heldForRecovery: [], unclear: [],
    });
    expect(res.failed).toBe(1);
    expect(res.results[0]!.note).toBe("path_outside_workspace");
  });

  it("leaves a repo Pathrule never touched exactly as it was", async () => {
    const files = { "CLAUDE.md": "# Mine alone\n", ".gitignore": "node_modules\n" };
    const root = await repo(files);
    const res = await applyEject(root, await planEject(root));
    expect(res.results).toEqual([]);
    for (const [rel, body] of Object.entries(files)) {
      expect(await readFile(join(root, rel), "utf8"), rel).toBe(body);
    }
  });
});

// What a v1 setup leaves in a project, taken back to the bytes the person had before it.
describe("eject after a setup: nothing of Pathrule's stays, nothing of the person's changes", () => {
  const hookEntry = { type: "command", command: "/home/pat/.pathrule/bin/pathrule-hook.js" };

  it("removes the rules folder, Codex's config block and Pathrule's own settings file", async () => {
    const userToml = 'model = "o4"\n';
    const userSettings = '{\n  "permissions": { "allow": ["Bash(ls:*)"] }\n}\n';
    const root = await repo({
      ".claude/settings.json": userSettings,
      ".claude/settings.local.json": JSON.stringify({ hooks: { SessionStart: [{ hooks: [hookEntry] }] } }, null, 2),
      ".claude/rules/pathrule/workspace.md": "<!-- Pathrule managed (knowledge) — compiled -->\n# Project instructions (Pathrule)\n",
      ".claude/rules/pathrule/apps-api.md": '---\npaths:\n  - "apps/api/**"\n---\n<!-- Pathrule managed (knowledge) -->\nx\n',
      ".claude/rules/pathrule/manifest.json": '{"_": "# >>> Pathrule managed: binding manifest"}\n',
      ".claude/rules/pathrule/.gitignore": "# Pathrule managed — compiled instructions, regenerated on sync.\n*\n",
      ".codex/config.toml": `${userToml}\n# >>> Pathrule managed (codex hook activation) >>>\n[features]\nhooks = true\n# <<< Pathrule managed <<<\n`,
      ".codex/hooks.json": JSON.stringify({ hooks: { SessionStart: [{ hooks: [hookEntry] }] } }),
      ".pathrule/managed-files.json": JSON.stringify({ schema_version: 1, files: [{ path: ".claude/settings.local.json", owner: "cli", owner_version: "1", updated_at: "x" }] }),
      "CLAUDE.md": "# Mine\n",
    });

    const plan = await planEject(root);
    const result = await applyEject(root, plan);
    expect(result.failed).toBe(0);

    expect(await readFile(join(root, ".codex/config.toml"), "utf8")).toBe(userToml);
    expect(await readFile(join(root, ".claude/settings.json"), "utf8")).toBe(userSettings);
    expect(await readFile(join(root, "CLAUDE.md"), "utf8")).toBe("# Mine\n");
    for (const gone of [".claude/settings.local.json", ".claude/rules", ".codex/hooks.json", ".pathrule"]) {
      await expect(readFile(join(root, gone), "utf8"), gone).rejects.toThrow();
    }
    // Run again: nothing left to do.
    expect((await planEject(root)).actions).toEqual([]);
  });

  it("leaves a settings file it cannot read exactly as it is", async () => {
    const jsonc = '{\n  // mine\n  "hooks": { "SessionStart": [{ "hooks": [{ "command": "pathrule-hook.js" }] }] },\n}\n';
    const root = await repo({ ".claude/settings.json": jsonc });
    const result = await applyEject(root, await planEject(root));
    expect(result.failed).toBe(0);
    expect(await readFile(join(root, ".claude/settings.json"), "utf8")).toBe(jsonc);
  });

  it("never removes a file of the person's in the rules folder", async () => {
    const root = await repo({ ".claude/rules/pathrule/mine.md": "# my own rule\n" });
    await applyEject(root, await planEject(root));
    expect(await readFile(join(root, ".claude/rules/pathrule/mine.md"), "utf8")).toBe("# my own rule\n");
  });
});
