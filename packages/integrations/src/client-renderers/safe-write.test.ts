// safe-write is the single place that decides whether an on-disk file belongs
// to Pathrule or to the user. Every companion file's fate runs through it, so
// it gets its own unit suite: the scenario tests prove end-to-end behaviour,
// these prove the decision itself.

import { afterAll, beforeAll, describe, expect, it } from "vitest";
import { mkdtemp, readdir, writeFile } from "node:fs/promises";
import { existsSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";

import { __resetHookCommandForTests, setHookCommand } from "../hook-supervisor/hook-command.js";

beforeAll(() => setHookCommand("/tmp/pathrule-hook.js"));
afterAll(() => __resetHookCommandForTests());

import { isPathruleManaged, prepareSafeWrite } from "./safe-write.js";
import { backupRelativePath } from "@pathrule/core/paths/workspace-files.js";
import { hasRegion, stripRegion } from "@pathrule/core/paths/region.js";

const ROOT_PROTOCOL_BANNER =
  "<!-- managed by Pathrule — do not edit this file manually. Cloud state is authoritative. -->";
const KNOWLEDGE_BANNER =
  "<!-- Pathrule managed (knowledge) — compiled from workspace knowledge; do not edit. -->";
const CLIENT_BODY_BANNER = "<!-- Pathrule managed — do not edit; cloud state is authoritative. -->";

const USER_CLAUDE = `# Acme Platform

See @docs/architecture.md for the service map.

## Conventions
Use camelCase.
`;

async function tmpRoot(): Promise<string> {
  return mkdtemp(join(tmpdir(), "pathrule-safe-write-"));
}

describe("isPathruleManaged", () => {
  it("recognises every banner Pathrule emits", () => {
    expect(isPathruleManaged(`${ROOT_PROTOCOL_BANNER}\n# Pathrule Workspace\n`)).toBe(true);
    expect(isPathruleManaged(`${KNOWLEDGE_BANNER}\n# Project knowledge\n`)).toBe(true);
    expect(isPathruleManaged(`${CLIENT_BODY_BANNER}\n# Pathrule integration\n`)).toBe(true);
  });

  it("does not claim a user's file", () => {
    expect(isPathruleManaged(USER_CLAUDE)).toBe(false);
    expect(isPathruleManaged("")).toBe(false);
    // Merely mentioning Pathrule in prose is not ownership.
    expect(isPathruleManaged("We use Pathrule for shared memory.\n")).toBe(false);
  });
});

// ─── merge-region: the default for filenames the client dictates ─────────────

describe("prepareSafeWrite: user-canonical instruction files", () => {
  it("keeps the user's file in place and adds an anchored region", async () => {
    const root = await tmpRoot();
    await writeFile(join(root, "CLAUDE.md"), USER_CLAUDE, "utf8");

    const res = await prepareSafeWrite({
      workspaceRoot: root,
      relativePath: "CLAUDE.md",
      renderedBody: `${ROOT_PROTOCOL_BANNER}\nPATHRULE SECTION\n`,
      existingBody: USER_CLAUDE,
    });

    expect(res.backupPath).toBeNull(); // nothing is moved aside
    expect(res.finalBody).not.toBeNull();
    expect(res.finalBody).toContain("PATHRULE SECTION");
    // The user's instructions still reach the agent, byte-identical.
    expect(stripRegion(res.finalBody!)).toBe(USER_CLAUDE.trim());
    // Including their @import chain, which a takeover would have severed.
    expect(res.finalBody).toContain("@docs/architecture.md");
  });

  it("replaces only the region on re-render, then goes quiet", async () => {
    const root = await tmpRoot();
    const first = await prepareSafeWrite({
      workspaceRoot: root,
      relativePath: "AGENTS.md",
      renderedBody: "SECTIONONE",
      existingBody: USER_CLAUDE,
    });

    const second = await prepareSafeWrite({
      workspaceRoot: root,
      relativePath: "AGENTS.md",
      renderedBody: "SECTIONTWO",
      existingBody: first.finalBody,
    });
    expect(second.finalBody).toContain("SECTIONTWO");
    expect(second.finalBody).not.toContain("SECTIONONE");
    expect(stripRegion(second.finalBody!)).toBe(USER_CLAUDE.trim());

    // Same input again → no write at all.
    const third = await prepareSafeWrite({
      workspaceRoot: root,
      relativePath: "AGENTS.md",
      renderedBody: "SECTIONTWO",
      existingBody: second.finalBody,
    });
    expect(third).toEqual({ finalBody: null, backupPath: null });
  });

  it("writes a standalone anchored file when none exists", async () => {
    const root = await tmpRoot();
    const res = await prepareSafeWrite({
      workspaceRoot: root,
      relativePath: "AGENTS.md",
      renderedBody: "FRESH SECTION",
      existingBody: null,
    });
    expect(res.backupPath).toBeNull();
    expect(hasRegion(res.finalBody!)).toBe(true);
    expect(stripRegion(res.finalBody!)).toBe("");
  });

  it("converts a legacy Pathrule-owned file (banner, no anchors) in place", async () => {
    const root = await tmpRoot();
    const legacy = `${CLIENT_BODY_BANNER}\n# Pathrule integration\n\nold protocol text\n`;

    const res = await prepareSafeWrite({
      workspaceRoot: root,
      relativePath: "AGENTS.md",
      renderedBody: "NEW SECTION",
      existingBody: legacy,
    });

    expect(res.backupPath).toBeNull();
    expect(hasRegion(res.finalBody!)).toBe(true);
    expect(res.finalBody).toContain("NEW SECTION");
    // That body was entirely ours, so nothing is preserved outside the region.
    expect(stripRegion(res.finalBody!)).toBe("");
    expect(res.finalBody).not.toContain("old protocol text");
  });

  it("applies to nested instruction files in a monorepo", async () => {
    const root = await tmpRoot();
    const userNested = "# API package\n\nNode 20 only. Never import packages/web.\n";

    const res = await prepareSafeWrite({
      workspaceRoot: root,
      relativePath: "packages/api/CLAUDE.md",
      renderedBody: "API KNOWLEDGE",
      existingBody: userNested,
    });

    expect(res.backupPath).toBeNull();
    expect(res.finalBody).toContain("Never import packages/web");
    expect(res.finalBody).toContain("API KNOWLEDGE");
  });

  it("keeps a dotfile's user content too", async () => {
    const root = await tmpRoot();
    const res = await prepareSafeWrite({
      workspaceRoot: root,
      relativePath: ".cursorrules",
      renderedBody: "PATHRULE RULES",
      existingBody: "Always write TypeScript strict mode.\n",
    });
    expect(res.backupPath).toBeNull();
    expect(res.finalBody).toContain("Always write TypeScript strict mode.");
    expect(res.finalBody).toContain("PATHRULE RULES");
  });

  it("never creates a backup file for these paths", async () => {
    const root = await tmpRoot();
    await writeFile(join(root, "AGENTS.md"), USER_CLAUDE, "utf8");
    await prepareSafeWrite({
      workspaceRoot: root,
      relativePath: "AGENTS.md",
      renderedBody: "SECTION",
      existingBody: USER_CLAUDE,
    });
    expect(existsSync(join(root, ".pathrule"))).toBe(false);
    expect(await readdir(root)).toEqual(["AGENTS.md"]);
  });
});

// ─── overwrite: filenames Pathrule invented ─────────────────────────────────

describe("prepareSafeWrite: Pathrule-invented filenames", () => {
  it("overwrites without backup", async () => {
    const root = await tmpRoot();
    const res = await prepareSafeWrite({
      workspaceRoot: root,
      relativePath: ".claude/rules/pathrule-protocol.md",
      renderedBody: "new protocol\n",
      existingBody: "old protocol\n",
    });
    expect(res).toEqual({ finalBody: "new protocol\n", backupPath: null });
  });

  it("is a no-op when the bytes already match", async () => {
    const root = await tmpRoot();
    const res = await prepareSafeWrite({
      workspaceRoot: root,
      relativePath: ".windsurf/rules/pathrule-protocol.md",
      renderedBody: "same\n",
      existingBody: "same\n",
    });
    expect(res).toEqual({ finalBody: null, backupPath: null });
  });
});

// ─── merge: structured config ────────────────────────────────────────────────

describe("prepareSafeWrite: structured config", () => {
  it("preserves unrelated user keys in settings.json", async () => {
    const root = await tmpRoot();
    const userSettings = JSON.stringify(
      { theme: "dark", permissions: { allow: ["Bash"] } },
      null,
      2,
    );

    const res = await prepareSafeWrite({
      workspaceRoot: root,
      relativePath: ".claude/settings.json",
      renderedBody: "{}",
      existingBody: userSettings,
    });

    const merged = JSON.parse(res.finalBody ?? userSettings) as Record<string, unknown>;
    expect(merged.theme).toBe("dark");
    expect(merged.permissions).toEqual({ allow: ["Bash"] });
  });
});

// ─── the backup vault layout, owned by @pathrule/core ───────────────────────
//
// safe-write itself no longer takes a file over: `merge-region` made the
// backup-on-first-write regime dead code and it was removed. The vault contract
// stays because the recovery flow still reads repos an older Pathrule damaged.

describe("backup vault layout", () => {
  it("preserves the original path so same-named files cannot collide", () => {
    expect(backupRelativePath("packages/api/CLAUDE.md")).toBe(
      ".pathrule/backups/packages/api/CLAUDE.md",
    );
    expect(backupRelativePath("packages/web/CLAUDE.md")).toBe(
      ".pathrule/backups/packages/web/CLAUDE.md",
    );
    // A dotfile keeps its real name: no `backup..cursorrules`.
    expect(backupRelativePath(".cursorrules")).toBe(".pathrule/backups/.cursorrules");
  });

  it("is not created by a normal sync, because nothing is moved aside", async () => {
    const root = await tmpRoot();
    await writeFile(join(root, "CLAUDE.md"), USER_CLAUDE, "utf8");
    await prepareSafeWrite({
      workspaceRoot: root,
      relativePath: "CLAUDE.md",
      renderedBody: "SECTION",
      existingBody: USER_CLAUDE,
    });
    expect(existsSync(join(root, ".pathrule"))).toBe(false);
  });
});
