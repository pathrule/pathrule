// The automatic half of the migration. The line it must not cross: only files
// that provably hold nothing of the user's.
import { mkdir, mkdtemp, readFile, rm, stat, writeFile } from "node:fs/promises";
import { existsSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { afterEach, describe, expect, it } from "vitest";

import {
  __resetLegacySweepForTests,
  sweepPathruleOwnLeftovers,
} from "./legacy-sweep.js";

const OURS = "<!-- managed by Pathrule — do not edit this file manually. -->\n# Pathrule Workspace\n";
const KNOWLEDGE = "<!-- Pathrule managed (knowledge) -->\n# Project knowledge\n";

const roots: string[] = [];
afterEach(async () => {
  __resetLegacySweepForTests();
  await Promise.all(roots.splice(0).map((r) => rm(r, { recursive: true, force: true })));
});

async function repo(files: Record<string, string>): Promise<string> {
  const root = await mkdtemp(join(tmpdir(), "pathrule-sweep-"));
  roots.push(root);
  for (const [rel, body] of Object.entries(files)) {
    const abs = join(root, rel);
    await mkdir(join(abs, ".."), { recursive: true });
    await writeFile(abs, body);
  }
  return root;
}

const exists = async (root: string, rel: string) => {
  try {
    await stat(join(root, rel));
    return true;
  } catch {
    return false;
  }
};

describe("sweepPathruleOwnLeftovers", () => {
  // The measured shape of this repo: seven identical copies of Pathrule's own
  // output, all committed to git, all previously offered to the user as their
  // lost work.
  it("removes Pathrule's own leftover backups without being asked", async () => {
    const files: Record<string, string> = { "packages/mobile/CLAUDE.md": KNOWLEDGE };
    for (const suffix of ["", ".1", ".2", ".3", ".4", ".5", ".6"]) {
      files[`packages/mobile/backup.CLAUDE.md${suffix}`] = OURS;
    }
    const root = await repo(files);

    const res = await sweepPathruleOwnLeftovers(root);

    expect(res.removed).toHaveLength(7);
    expect(res.held).toEqual([]);
    for (const suffix of ["", ".1", ".6"]) {
      expect(await exists(root, `packages/mobile/backup.CLAUDE.md${suffix}`)).toBe(false);
    }
    // The live file is untouched: the sweep removes leftovers, not knowledge.
    expect(await readFile(join(root, "packages/mobile/CLAUDE.md"), "utf8")).toBe(KNOWLEDGE);
  });

  it("never removes a backup holding the user's content, and reports it instead", async () => {
    const root = await repo({
      "backup.AGENTS.md": "# The user's real instructions\n",
      "AGENTS.md": KNOWLEDGE,
    });

    const res = await sweepPathruleOwnLeftovers(root);

    expect(res.removed).toEqual([]);
    expect(res.held).toEqual(["backup.AGENTS.md"]);
    expect(await readFile(join(root, "backup.AGENTS.md"), "utf8")).toBe(
      "# The user's real instructions\n",
    );
  });

  it("separates the two in one pass", async () => {
    const root = await repo({
      "backup.AGENTS.md": "# mine\n",
      "AGENTS.md": KNOWLEDGE,
      "packages/api/backup.CLAUDE.md": OURS,
      "packages/api/CLAUDE.md": KNOWLEDGE,
    });

    const res = await sweepPathruleOwnLeftovers(root);

    expect(res.removed).toEqual(["packages/api/backup.CLAUDE.md"]);
    expect(res.held).toEqual(["backup.AGENTS.md"]);
  });

  it("runs once per workspace per process, because a migration is not a sync step", async () => {
    const root = await repo({ "backup.CLAUDE.md": OURS, "CLAUDE.md": KNOWLEDGE });

    const first = await sweepPathruleOwnLeftovers(root);
    const second = await sweepPathruleOwnLeftovers(root);

    expect(first.ran).toBe(true);
    expect(first.removed).toEqual(["backup.CLAUDE.md"]);
    expect(second.ran).toBe(false);
    expect(second.removed).toEqual([]);
  });

  it("does nothing at all in a repo with no leftovers", async () => {
    const root = await repo({ "CLAUDE.md": "# Mine alone\n" });
    const res = await sweepPathruleOwnLeftovers(root);
    expect(res).toEqual({ removed: [], held: [], ran: true });
    expect(await readFile(join(root, "CLAUDE.md"), "utf8")).toBe("# Mine alone\n");
  });

  it("removes Pathrule-named files no renderer owns any more", async () => {
    const root = await repo({});
    const dir = join(root, ".agents", "rules");
    await mkdir(dir, { recursive: true });
    // Both carry the managed marker, i.e. they are our output.
    await writeFile(
      join(dir, "pathrule-protocol.md"),
      "<!-- Pathrule managed — do not edit; cloud state is authoritative. -->\n# Pathrule Protocol\n",
    );
    await writeFile(
      join(dir, "pathrule-knowledge.md"),
      "<!-- Pathrule managed (knowledge) — compiled from workspace knowledge; do not edit; regenerated on sync. -->\n# Workspace knowledge\n",
    );

    const result = await sweepPathruleOwnLeftovers(root);

    expect(result.ran).toBe(true);
    expect(result.removed).toContain(".agents/rules/pathrule-protocol.md");
    expect(result.removed).toContain(".agents/rules/pathrule-knowledge.md");
    expect(existsSync(join(dir, "pathrule-protocol.md"))).toBe(false);
  });

  it("leaves a same-named file alone when it is not ours", async () => {
    const root = await repo({});
    const dir = join(root, ".agents", "rules");
    await mkdir(dir, { recursive: true });
    // No managed marker: someone else's file that happens to sit at our path.
    const theirs = join(dir, "pathrule-protocol.md");
    await writeFile(theirs, "# our team's own notes about pathrule\n");

    const result = await sweepPathruleOwnLeftovers(root);

    expect(result.removed).not.toContain(".agents/rules/pathrule-protocol.md");
    expect(existsSync(theirs)).toBe(true);
  });
});
