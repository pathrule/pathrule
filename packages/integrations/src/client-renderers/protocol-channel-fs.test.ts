// The disk edge, including the two properties that decide whether this is safe
// to put on the per-write path: with the switch off it does NO I/O at all, and
// with it on the expensive half runs once per workspace rather than once per
// write.
import { mkdir, mkdtemp, rm, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { afterEach, describe, expect, it } from "vitest";

import {
  RECOVERY_LATCH_TTL_MS,
  invalidateRecoveryLatch,
  resolveWorkspaceProtocolChannel,
  signatureModeEnabled,
} from "./protocol-channel-fs.js";

const roots: string[] = [];
afterEach(async () => {
  invalidateRecoveryLatch();
  await Promise.all(roots.splice(0).map((r) => rm(r, { recursive: true, force: true, maxRetries: 10, retryDelay: 100 })));
});

const HOOK_CONFIG = JSON.stringify({
  hooks: { UserPromptSubmit: [{ hooks: [{ type: "command", command: "/x/pathrule-hook.js" }] }] },
});

async function workspace(opts: { hook?: boolean; backup?: "user" | "ours" } = {}) {
  const root = await mkdtemp(join(tmpdir(), "pathrule-channel-fs-"));
  const home = await mkdtemp(join(tmpdir(), "pathrule-channel-home-"));
  roots.push(root, home);
  if (opts.hook) {
    await mkdir(join(root, ".codex"), { recursive: true });
    await writeFile(join(root, ".codex", "hooks.json"), HOOK_CONFIG);
  }
  if (opts.backup) {
    const body =
      opts.backup === "user"
        ? "# The user's real instructions\n"
        : "<!-- managed by Pathrule — do not edit this file manually. -->\n# ours\n";
    await writeFile(join(root, "backup.AGENTS.md"), body);
    await writeFile(
      join(root, "AGENTS.md"),
      "<!-- managed by Pathrule — do not edit this file manually. -->\n# knowledge\n",
    );
  }
  return { root, home };
}

const ON = { PATHRULE_SIGNATURE_MODE: "on" } as NodeJS.ProcessEnv;

describe("signatureModeEnabled", () => {
  // Default flipped to ON once the measurement was in (see the module comment).
  // The kill switch has to keep working, and it has to be the ONLY thing that
  // turns it off: a typo like "yes-ish" must not silently disable the mode, or a
  // misconfigured deploy would go back to writing 26 files with nothing reporting
  // it.
  it("is on by default and only an explicit off switches it off", () => {
    for (const v of ["off", "0", "false", "OFF", " False "]) {
      expect(signatureModeEnabled({ PATHRULE_SIGNATURE_MODE: v } as NodeJS.ProcessEnv), String(v)).toBe(false);
    }
    for (const v of [undefined, "", " ", "on", "1", "true", "ON", " True ", "yes-ish"]) {
      expect(signatureModeEnabled({ PATHRULE_SIGNATURE_MODE: v } as NodeJS.ProcessEnv), String(v)).toBe(true);
    }
  });
});

describe("resolveWorkspaceProtocolChannel", () => {
  // The cost claim (no I/O with the switch off) is measured in the module comment;
  // what a test can prove is the property that makes it true: with the switch off,
  // NOTHING on disk can change the answer. Built here with the richest possible
  // workspace, a hook installed and a real backup pending, both of which the
  // switch-on path reads.
  it("is decided by the switch alone: no disk state can change the answer", async () => {
    const { root, home } = await workspace({ hook: true, backup: "user" });
    for (const env of [{ PATHRULE_SIGNATURE_MODE: "off" }] as NodeJS.ProcessEnv[]) {
      const channel = await resolveWorkspaceProtocolChannel({
        workspaceRoot: root,
        enabled: ["codex", "claude-code"],
        env,
        home,
      });
      expect(channel).toEqual({ signatureClients: [], off: "flag_off" });
    }
  });

  it("turns the channel on for a client whose hook is installed", async () => {
    const { root, home } = await workspace({ hook: true });
    const channel = await resolveWorkspaceProtocolChannel({
      workspaceRoot: root,
      enabled: ["codex"],
      env: ON,
      home,
    });
    expect(channel.signatureClients).toEqual(["codex"]);
    expect(channel.protocol ?? "").toContain("pathrule_get_context");
    expect(channel.off).toBeUndefined();
  });

  it("stays off, and says why, when no hook would deliver the protocol", async () => {
    const { root, home } = await workspace({ hook: false });
    const channel = await resolveWorkspaceProtocolChannel({
      workspaceRoot: root,
      enabled: ["codex"],
      env: ON,
      home,
    });
    expect(channel).toEqual({ signatureClients: [], off: "no_hook" });
  });

  it("holds while the user's content is still in a backup", async () => {
    const { root, home } = await workspace({ hook: true, backup: "user" });
    const channel = await resolveWorkspaceProtocolChannel({
      workspaceRoot: root,
      enabled: ["codex"],
      env: ON,
      home,
    });
    expect(channel).toEqual({ signatureClients: [], off: "pending_recovery" });
  });

  it("does not hold for a backup that is only Pathrule's own output", async () => {
    const { root, home } = await workspace({ hook: true, backup: "ours" });
    const channel = await resolveWorkspaceProtocolChannel({
      workspaceRoot: root,
      enabled: ["codex"],
      env: ON,
      home,
    });
    expect(channel.signatureClients).toEqual(["codex"]);
  });

  // The latch, proved by behaviour rather than by counting syscalls: change the
  // disk under it and the answer must NOT move inside the TTL, then must move
  // once the TTL passes. A per-write walk would fail the first half; a latch with
  // no expiry would fail the second.
  it("answers the expensive question from a latch, and lets it expire", async () => {
    const { root, home } = await workspace({ hook: true, backup: "user" });
    const call = (now: number) =>
      resolveWorkspaceProtocolChannel({
        workspaceRoot: root,
        enabled: ["codex"],
        env: ON,
        home,
        now,
      });

    expect((await call(1_000)).off).toBe("pending_recovery");
    await rm(join(root, "backup.AGENTS.md"));

    // Inside the TTL the latch answers, so the removal is invisible.
    expect((await call(1_000 + RECOVERY_LATCH_TTL_MS - 1)).off).toBe("pending_recovery");
    // Past it, the walk runs again and the truth changes.
    expect((await call(1_000 + RECOVERY_LATCH_TTL_MS + 1)).signatureClients).toEqual(["codex"]);
  });

  it("re-reads immediately once a recovery action invalidates the latch", async () => {
    const { root, home } = await workspace({ hook: true, backup: "user" });
    const first = await resolveWorkspaceProtocolChannel({
      workspaceRoot: root,
      enabled: ["codex"],
      env: ON,
      home,
      now: 1,
    });
    expect(first.off).toBe("pending_recovery");

    // The user restores it, which removes the backup.
    await rm(join(root, "backup.AGENTS.md"));
    // Without invalidation the latch still says pending inside the TTL.
    const stale = await resolveWorkspaceProtocolChannel({
      workspaceRoot: root,
      enabled: ["codex"],
      env: ON,
      home,
      now: 2,
    });
    expect(stale.off).toBe("pending_recovery");

    invalidateRecoveryLatch(root);
    const fresh = await resolveWorkspaceProtocolChannel({
      workspaceRoot: root,
      enabled: ["codex"],
      env: ON,
      home,
      now: 3,
    });
    expect(fresh.signatureClients).toEqual(["codex"]);
  });
});
