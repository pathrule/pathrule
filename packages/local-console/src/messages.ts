export type ConsoleMessages = typeof consoleMessages;
/** A locale's version of the console's strings, any subset. */
export type ConsoleCatalog = DeepPartial<ConsoleMessages>;

export function useConsoleMessages() {
  return useMessages("console", consoleMessages);
}

/** Locales the console ships catalogs for. English is the source and the default. */
export const CONSOLE_LOCALES: readonly string[] = ["en"];

/** The first preferred language the console has, else English: strings and formats agree. */
export function pickLocale(preferred: readonly string[]): string {
  for (const tag of preferred) {
    const base = tag.toLowerCase().split("-")[0] ?? "";
    if (CONSOLE_LOCALES.includes(base)) return base;
  }
  return "en";
}
